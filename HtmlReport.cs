using System.Net;
using System.Text;
using USBScope.Usb;

namespace USBScope;

/// <summary>Builds an HTML report with the device table and context data.</summary>
public static class HtmlReport
{
    public static string Build(IEnumerable<USBScopeInfo> devices, DateTime when)
    {
        var list = devices.ToList();
        var sb = new StringBuilder();
        sb.AppendLine("<!DOCTYPE html>");
        sb.AppendLine("<html lang=\"en\">");
        sb.AppendLine("<head><meta charset=\"utf-8\">");
        sb.AppendLine("<title>USBScope &mdash; USB device report</title>");
        sb.AppendLine("<style>");
        sb.AppendLine("body{font-family:Segoe UI,Arial,sans-serif;font-size:14px;margin:24px;color:#222}");
        sb.AppendLine("h1{font-size:22px;margin-bottom:2px}");
        sb.AppendLine(".meta{color:#555;margin-bottom:12px}");
        sb.AppendLine("table{border-collapse:collapse;width:100%}");
        sb.AppendLine("th,td{border:1px solid #ccc;padding:6px 8px;text-align:left}");
        sb.AppendLine("th{background:#f0f0f0}");
        sb.AppendLine(".footer{margin-top:12px;color:#777;font-size:12px}");
        sb.AppendLine("</style></head>");
        sb.AppendLine("<body>");
        sb.AppendLine("<h1>USBScope &mdash; connected USB devices</h1>");
        sb.Append(" <p class=\"meta\">Detected on ").Append(when.ToString("yyyy-MM-dd HH:mm:ss"));
        sb.Append(" &mdash; Computer: ").Append(Encode(Environment.MachineName));
        sb.Append(" &mdash; ").Append(Encode(Environment.OSVersion.VersionString));
        sb.Append(" &mdash; Devices: ").Append(list.Count).AppendLine("</p>");

        sb.AppendLine("<ul>");
        foreach (var g in list.GroupBy(d => d.Standard).OrderByDescending(g => g.Max(d => d.SpeedRank)))
        {
            sb.Append("  <li>").Append(Encode(g.Key)).Append(": ").Append(g.Count()).AppendLine("</li>");
        }
        sb.AppendLine("</ul>");

        sb.AppendLine("<table>");
        sb.AppendLine("<tr><th>Device</th><th>Marca</th><th>VID / PID</th><th>USB standard</th><th>Speed</th><th>Hub / Port</th><th>Status</th></tr>");
        foreach (var d in list)
        {
            sb.Append("  <tr style=\"color:").Append(RankColor(d.SpeedRank)).Append("\">");
            sb.Append("<td>").Append(Encode(d.DeviceName)).Append("</td>");
            sb.Append("<td>").Append(Encode(d.Vendor)).Append("</td>");
            sb.Append("<td>").Append(Encode(d.VidPid)).Append("</td>");
            sb.Append("<td>").Append(Encode(d.Standard)).Append("</td>");
            sb.Append("<td>").Append(Encode(d.SpeedText)).Append("</td>");
            sb.Append("<td>").Append(Encode(d.Location)).Append("</td>");
            sb.Append("<td>").Append(Encode(d.Status)).Append("</td>");
            sb.AppendLine("</tr>");
        }
        sb.AppendLine("</table>");
        sb.AppendLine("<p class=\"footer\">Generated by USBScope — Francesco Ferrara, Tecnico del Computer (www.elenafrancesco.org).</p>");
        sb.AppendLine("</body>");
        sb.AppendLine("</html>");
        return sb.ToString();
    }

    private static string Encode(string s) => WebUtility.HtmlEncode(s);

    private static string RankColor(int rank) => rank switch
    {
        -1 => "#8A8A8A",
        0 => "#A63232",
        1 => "#B35C14",
        2 => "#7A6A10",
        3 => "#1E6B34",
        _ => "#14532D",
    };
}
